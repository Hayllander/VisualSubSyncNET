using System.Globalization;
using System.Text;
using VisualSubSync.Core.Text;
using VisualSubSync.Core.Timing;
using VisualSubSync.Core.Web;

namespace VisualSubSync.Core.Plugins;

/// <summary>
/// miExportToHTMLClick (ErrorReportFormUnit.pas): a página com uma linha por erro. As mensagens e o
/// texto vão em UTF-8 (UTF8Encode); o nome do projeto e o resto, como string do Delphi, em ANSI.
/// </summary>
public static class ErrorReportHtml
{
    private const string Head =
        "<head>\r\n" +
        "<meta http-equiv=\"Content-Type\" content=\"text/html; charset=utf-8\" >\r\n" +
        "<title>VisualSubSync error report</title>\r\n" +
        "<style type=\"text/css\">\r\n" +
        "body { text-align: center;\t}\r\n" +
        "td { padding-left: 5px; padding-right: 5px; }\r\n" +
        ".MainColumn { width: 90%; margin: auto; }\r\n" +
        ".HeaderColor { background-color: #BBDDFF; }\r\n" +
        ".HeaderError { background-color: #BBDDFF; }\r\n" +
        ".HeaderIndex { background-color: #BBDDFF; }\r\n" +
        ".HeaderFromTo { background-color: #BBDDFF; }\r\n" +
        ".HeaderText { background-color: #DDEEFF; }\r\n" +
        ".CellIndex { background-color: #DDDDDD; text-align: center; }\r\n" +
        ".CellFromTo { background-color: #DDDDDD; text-align: center; white-space: nowrap; }\r\n" +
        ".CellText { background-color: #EEEEEE; }\r\n" +
        ".CellError { background-color: #DDDDDD; white-space: nowrap; }\r\n" +
        ".Title { font-size: 180%; margin-bottom: 1em; }\r\n" +
        ".Footer { text-align: center; font-size: 60%; margin-top: 1em; }\r\n" +
        ".Project { text-align: left; font-size: 120%; margin-bottom: 1em; }\r\n" +
        "</style>\r\n" +
        "</head>";

    private const string TableHeader =
        "<tr>\r\n" +
        "<th class=\"HeaderColor\">Color</th>\r\n" +
        "<th class=\"HeaderError\">Error</th>\r\n" +
        "<th class=\"HeaderIndex\">Index</th>\r\n" +
        "<th class=\"HeaderFromTo\">From - To</th>\r\n" +
        "<th class=\"HeaderText\">Text</th>\r\n" +
        "</tr>";

    /// <param name="indexOf">Node.Index da legenda do erro.</param>
    public static void Write(Stream stream, IEnumerable<ErrorItem> errors, Func<ErrorItem, int> indexOf, string projectFileName, string version)
    {
        ArgumentNullException.ThrowIfNull(stream);
        ArgumentNullException.ThrowIfNull(errors);
        ArgumentNullException.ThrowIfNull(indexOf);
        var ansi = TextFileReader.Ansi;
        void Line(params byte[][] parts)
        {
            foreach (var part in parts)
            {
                stream.Write(part);
            }

            stream.Write("\r\n"u8);
        }

        byte[] A(string s) => ansi.GetBytes(s);
        byte[] U(string s) => Encoding.UTF8.GetBytes(s);

        Line(A("<html>"));
        Line(A(Head));
        Line(A("<body>"));
        Line(A("<div class=\"MainColumn\">"));
        Line(A("<div class=\"Title\">VisualSubSync error report</div>"));
        Line(A("<div class=\"Project\">Project : " + projectFileName + "</div>"));
        Line(A("<table style=\"margin: auto;\">"));
        Line(A(TableHeader));
        foreach (var error in errors)
        {
            string color = ErrorPlugin.ToTColor(error.Color).ToString("X6", CultureInfo.InvariantCulture);
            Line(
                A("<tr><td style=\"border: 1px solid black; background-color: #" + color + ";\">&nbsp;&nbsp;</td>"),
                A("<td class=\"CellError\">"), U(error.PluginMessage), A("<br><i>"), U(error.ErrorMessage), A("</i></td>"),
                A("<td class=\"CellIndex\">" + (indexOf(error) + 1).ToString(CultureInfo.InvariantCulture) + "</td>"),
                A("<td class=\"CellFromTo\">" + TimeFormat.ToVss(error.Subtitle.StartMs) + " - " + TimeFormat.ToVss(error.Subtitle.StopMs) + "</td>"),
                A("<td class=\"CellText\">"), U(PageProcessor.ConvertCrLfToBr(error.Subtitle.Text)), A("</td></tr>"));
        }

        Line(A("</table>"));
        Line(A("<div class=\"Footer\">Generated by <a href=\"http://visualsubsync.coreforge.org\">VisualSubSync</a> " + version + "</div>"));
        Line(A("</div>"));
        Line(A("</body>"));
        Line(A("</html>"));
    }
}
